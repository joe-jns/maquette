import { test, expect } from '@playwright/test'
import { launch } from './launch'
import { boxOf, centerOf, clickOn, scene, selection, settled } from './canvas'

test('clic, double-clic, Échap : on entre et on sort des cadres', async () => {
  const { app, page } = await launch([scene])
  await settled(page, 'tTitre')
  await clickOn(page, 'tTitre')
  expect(await selection(page)).toEqual(['fHero1'])
  const c = await centerOf(page, 'tTitre')
  await page.mouse.dblclick(c.x, c.y)
  expect(await selection(page)).toEqual(['tTitre'])
  await page.keyboard.press('Escape')
  expect(await selection(page)).toEqual(['fHero1'])
  await page.keyboard.press('Escape')
  expect(await selection(page)).toEqual([])
  await app.close()
})

test('Ctrl+clic sélectionne en profondeur ; Maj+clic ajoute et retire', async () => {
  const { app, page } = await launch([scene])
  await settled(page, 'tTitre')
  await clickOn(page, 'tSuite', ['Control'])
  expect(await selection(page)).toEqual(['tSuite'])
  await clickOn(page, 'rBleu1')
  await clickOn(page, 'rVert1', ['Shift'])
  expect(await selection(page)).toEqual(['rBleu1', 'rVert1'])
  await clickOn(page, 'rBleu1', ['Shift'])
  expect(await selection(page)).toEqual(['rVert1'])
  await app.close()
})

test('clic dans le vide désélectionne ; le lasso sélectionne ce qu’il touche', async () => {
  const { app, page } = await launch([scene])
  await settled(page, 'tTitre')
  await clickOn(page, 'rBleu1')
  const bleu = await boxOf(page, 'rBleu1')
  const vert = await boxOf(page, 'rVert1')
  await page.mouse.click(bleu.x - 20, bleu.y + bleu.height + 25)
  expect(await selection(page)).toEqual([])
  await page.mouse.move(bleu.x + 10, bleu.y + bleu.height + 30)
  await page.mouse.down()
  await page.mouse.move(vert.x + 20, vert.y + 20, { steps: 6 })
  await expect(page.getByTestId('marquee')).toBeVisible()
  await page.mouse.up()
  expect(await selection(page)).toEqual(['rBleu1', 'rVert1'])
  await expect(page.getByTestId('marquee')).toHaveCount(0)
  await app.close()
})

test('la sélection affiche 8 poignées et la taille ; Entrée, Tab, Ctrl+A', async () => {
  const { app, page } = await launch([scene])
  await settled(page, 'tTitre')
  await clickOn(page, 'rBleu1')
  await expect(page.locator('[data-handle]')).toHaveCount(8)
  await expect(page.getByTestId('size-label')).toHaveText('100 × 100')
  await page.keyboard.press('Tab')
  expect(await selection(page)).toEqual(['rVert1'])
  await clickOn(page, 'tTitre')
  await page.keyboard.press('Enter')
  expect(await selection(page)).toEqual(['tTitre'])
  await page.keyboard.press('Control+a')
  expect(await selection(page)).toEqual(['tTitre', 'tSuite', 'tTroisi'])
  await page.keyboard.press('Shift+Enter')
  expect(await selection(page)).toEqual(['fHero1'])
  await app.close()
})
